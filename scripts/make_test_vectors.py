"""Generates the cross-language test vectors used by the Java SDK tests.

Ed25519 is deterministic, so a header signed in Python with a fixed key,
body and timestamp must come out *byte-identical* when the Java SDK signs
the same inputs. The Java tests check that, and also check that Java
verifies Python's Merkle proofs and tree heads.

    python scripts/make_test_vectors.py          # rewrite the vectors file
    python scripts/make_test_vectors.py --check  # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import base64
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from sakshi.auth import create_authorization_header  # noqa: E402
from sakshi.crypto import KeyPair, b64e  # noqa: E402
from sakshi.merkle import MerkleTree, SignedTreeHead  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "java" / "src" / "test" / "resources" / "vectors.properties"


def build() -> str:
    keys = KeyPair.from_seed(b"cross-language-test")
    witness = KeyPair.from_seed(b"cross-language-witness")
    body = json.dumps({"context": {"action": "search", "bap_id": "paybuddy.app", "transaction_id": "t-1"},
                       "message": {"intent": {"item": {"descriptor": {"name": "चावल rice"}}}}},
                      separators=(",", ":"), ensure_ascii=False).encode()
    created = 1_760_000_000
    header = create_authorization_header(body, "paybuddy.app", "k1", keys.signing_private, created=created, ttl_s=30)

    tree = MerkleTree()
    for i in range(13):
        tree.append(f"entry-{i}".encode())
    sth = SignedTreeHead.create("witness.sakshi.network", 13, tree.root(), "k1", witness.signing_private,
                                timestamp=created)
    long_input = bytes(range(256)) * 2 + b"tail"

    v = {
        "blake.abc": hashlib.blake2b(b"abc", digest_size=64).hexdigest(),
        "blake.empty": hashlib.blake2b(b"", digest_size=64).hexdigest(),
        "blake.long.input": b64e(long_input),
        "blake.long": hashlib.blake2b(long_input, digest_size=64).hexdigest(),
        "blake.block": hashlib.blake2b(b"x" * 128, digest_size=64).hexdigest(),
        "key.private": keys.signing_private,
        "key.public": keys.signing_public,
        "auth.body": base64.b64encode(body).decode(),
        "auth.created": str(created),
        "auth.header": header,
        "merkle.leaf.6": b64e(tree.leaves[6]),
        "merkle.root.13": b64e(tree.root(13)),
        "merkle.inclusion.6.13": ",".join(b64e(p) for p in tree.inclusion_proof(6, 13)),
        "merkle.root.7": b64e(tree.root(7)),
        "merkle.consistency.7.13": ",".join(b64e(p) for p in tree.consistency_proof(7, 13)),
        "merkle.root.8": b64e(tree.root(8)),
        "merkle.consistency.8.13": ",".join(b64e(p) for p in tree.consistency_proof(8, 13)),
        "sth.log_id": sth.log_id, "sth.tree_size": str(sth.tree_size), "sth.root_hash": sth.root_hash,
        "sth.timestamp": str(sth.timestamp), "sth.signature": sth.signature,
        "witness.public": witness.signing_public,
    }
    lines = ["# Generated by scripts/make_test_vectors.py - do not edit by hand"]
    lines += [f"{k}={val}" for k, val in v.items()]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    content = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            sys.exit("test vectors are out of date: run python scripts/make_test_vectors.py")
        print("test vectors up to date")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(content, encoding="utf-8")
        print(f"wrote {OUT}")
