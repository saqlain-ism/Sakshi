package dev.sakshi;

import static org.junit.Assert.assertArrayEquals;
import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Base64;
import java.util.HexFormat;
import java.util.List;
import java.util.Properties;
import org.junit.BeforeClass;
import org.junit.Test;

/**
 * Proves the Java SDK and the Python implementation agree, using vectors generated by
 * {@code scripts/make_test_vectors.py}.
 */
public class InteropTest {
    private static final Properties V = new Properties();

    @BeforeClass
    public static void load() throws IOException {
        try (var in = InteropTest.class.getResourceAsStream("/vectors.properties")) {
            V.load(new InputStreamReader(in, StandardCharsets.UTF_8));
        }
    }

    private static String v(String k) {
        return V.getProperty(k);
    }

    private static byte[] b64(String s) {
        return Base64.getDecoder().decode(s);
    }

    private static List<byte[]> proof(String key) {
        List<byte[]> out = new ArrayList<>();
        for (String p : v(key).split(",")) {
            if (!p.isEmpty()) {
                out.add(b64(p));
            }
        }
        return out;
    }

    private static final AuthHeader.KeyResolver RESOLVER = (sub, uk) ->
            "paybuddy.app".equals(sub) && "k1".equals(uk)
                    ? new AuthHeader.KeyRecord(sub, uk, v("key.public"), 0, 4102444800.0, "SUBSCRIBED") : null;

    // ------------------------------------------------------------------ BLAKE2b
    @Test
    public void blake2bMatchesRfc7693AndPython() {
        assertEquals("ba80a53f981c4d0d6a2797b69f12f6e94c212f14685ac4b74b12bb6fdbffa2d1"
                + "7d87c5392aab792dc252d5de4533cc9518d38aa8dbf1925ab92386edd4009923",
                HexFormat.of().formatHex(Blake2b.digest512("abc".getBytes(StandardCharsets.US_ASCII))));
        assertEquals(v("blake.abc"), HexFormat.of().formatHex(Blake2b.digest512("abc".getBytes())));
        assertEquals(v("blake.empty"), HexFormat.of().formatHex(Blake2b.digest512(new byte[0])));
        assertEquals(v("blake.block"), HexFormat.of().formatHex(Blake2b.digest512("x".repeat(128).getBytes())));
        assertEquals(v("blake.long"), HexFormat.of().formatHex(Blake2b.digest512(b64(v("blake.long.input")))));
    }

    // -------------------------------------------------------------- auth header
    @Test
    public void javaSignsByteIdenticalToPython() {
        String header = AuthHeader.create(b64(v("auth.body")), "paybuddy.app", "k1", v("key.private"),
                Long.parseLong(v("auth.created")), 30);
        assertEquals(v("auth.header"), header);
    }

    @Test
    public void javaVerifiesPythonSignature() {
        long created = Long.parseLong(v("auth.created"));
        AuthHeader.Sender s = AuthHeader.verify(v("auth.header"), b64(v("auth.body")), RESOLVER, created + 1);
        assertEquals("paybuddy.app", s.subscriberId());
    }

    @Test
    public void tamperedBodyIsRejected() {
        byte[] body = b64(v("auth.body"));
        body[body.length - 3] ^= 1;
        expectCode("AUTH_BAD_SIGNATURE", () -> AuthHeader.verify(v("auth.header"), body, RESOLVER,
                Long.parseLong(v("auth.created")) + 1));
    }

    @Test
    public void expiredAndFutureSignaturesAreRejected() {
        long created = Long.parseLong(v("auth.created"));
        expectCode("AUTH_EXPIRED", () -> AuthHeader.verify(v("auth.header"), b64(v("auth.body")), RESOLVER, created + 600));
        expectCode("AUTH_NOT_YET_VALID", () -> AuthHeader.verify(v("auth.header"), b64(v("auth.body")), RESOLVER, created - 600));
    }

    @Test
    public void revokedAndUnknownKeysAreRejected() {
        long now = Long.parseLong(v("auth.created")) + 1;
        AuthHeader.KeyResolver revoked = (sub, uk) ->
                new AuthHeader.KeyRecord(sub, uk, v("key.public"), 0, 4102444800.0, "REVOKED");
        expectCode("AUTH_KEY_REVOKED", () -> AuthHeader.verify(v("auth.header"), b64(v("auth.body")), revoked, now));
        expectCode("AUTH_UNKNOWN_KEY", () -> AuthHeader.verify(v("auth.header"), b64(v("auth.body")), (s, u) -> null, now));
    }

    @Test
    public void malformedHeadersAreRejected() {
        expectCode("AUTH_MISSING", () -> AuthHeader.parse(""));
        expectCode("AUTH_MALFORMED", () -> AuthHeader.parse("Bearer abc"));
        expectCode("AUTH_MALFORMED", () -> AuthHeader.parse("Signature keyId=\"a|b\",algorithm=\"ed25519\""));
    }

    // ------------------------------------------------------------------- Merkle
    @Test
    public void javaVerifiesPythonInclusionProof() {
        byte[] leaf = b64(v("merkle.leaf.6"));
        byte[] root = b64(v("merkle.root.13"));
        assertArrayEquals(Merkle.leafHash("entry-6".getBytes()), leaf);
        assertTrue(Merkle.verifyInclusion(leaf, 6, 13, proof("merkle.inclusion.6.13"), root));
        assertFalse(Merkle.verifyInclusion(Merkle.leafHash("entry-X".getBytes()), 6, 13, proof("merkle.inclusion.6.13"), root));
        assertFalse(Merkle.verifyInclusion(leaf, 5, 13, proof("merkle.inclusion.6.13"), root));
    }

    @Test
    public void javaVerifiesPythonConsistencyProofs() {
        byte[] newRoot = b64(v("merkle.root.13"));
        assertTrue(Merkle.verifyConsistency(7, 13, b64(v("merkle.root.7")), newRoot, proof("merkle.consistency.7.13")));
        assertTrue(Merkle.verifyConsistency(8, 13, b64(v("merkle.root.8")), newRoot, proof("merkle.consistency.8.13")));
        // a rewritten history (different old root) must fail
        assertFalse(Merkle.verifyConsistency(7, 13, b64(v("merkle.root.8")), newRoot, proof("merkle.consistency.7.13")));
    }

    @Test
    public void javaVerifiesPythonSignedTreeHead() {
        Merkle.TreeHead head = new Merkle.TreeHead(v("sth.log_id"), Long.parseLong(v("sth.tree_size")),
                v("sth.root_hash"), Long.parseLong(v("sth.timestamp")), "k1", v("sth.signature"));
        assertTrue(head.verify(v("witness.public")));
        Merkle.TreeHead forged = new Merkle.TreeHead(head.logId(), head.treeSize() + 1, head.rootHash(),
                head.timestamp(), "k1", head.signature());
        assertFalse(forged.verify(v("witness.public")));
    }

    private static void expectCode(String code, Runnable r) {
        try {
            r.run();
            fail("expected " + code);
        } catch (SakshiException e) {
            assertEquals(code, e.code());
        }
    }
}
